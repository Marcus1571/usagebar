import SwiftUI

/// The Settings window, opened from the popover's gear button. Everything here is live: the
/// preview is the real label component drawn with the current data, so style choices are honest.
struct SettingsView: View {
    @ObservedObject var store: Store
    var onCheckForUpdates: (() -> Void)? = nil   // present only in packaged builds (Sparkle)

    private var visibleCount: Int {
        shownProviders(store.states, hidden: store.hiddenProviders).count
    }

    var body: some View {
        Form {
            Section("Menu bar") {
                Picker("Numbers", selection: $store.showLeft) {
                    Text("Left").tag(true)
                    Text("Used").tag(false)
                }
                .pickerStyle(.segmented).labelsHidden()

                Picker("Style", selection: $store.labelStyle) {
                    Text("Plain").tag(0)
                    Text("Outline").tag(1)
                    Text("Outline with dividers").tag(2)
                    Text("Pill").tag(3)
                    Text("Pill with outline").tag(4)
                }
                LabelView(states: store.states, showLeft: store.showLeft, hidden: store.hiddenProviders, dark: false, style: store.labelStyle)
                    .padding(.horizontal, 10).padding(.vertical, 6)
                    .background(RoundedRectangle(cornerRadius: 6).fill(Color(nsColor: .windowBackgroundColor)))
                    .overlay(RoundedRectangle(cornerRadius: 6).stroke(Color.primary.opacity(0.15)))
            }
            Section("Providers") {
                ForEach(Provider.allCases, id: \.self) { p in
                    Toggle(isOn: providerBinding(p)) {
                        HStack(spacing: 6) {
                            Image(systemName: p.symbol).font(.system(size: 12))
                            Text(p.title)
                            if store.states[p]?.notSignedIn == true {
                                Text("Not signed in").font(.caption).foregroundStyle(.secondary)
                            }
                        }
                    }
                    .disabled(store.hiddenProviders.contains(p) == false && visibleCount == 1)   // never blank the menu bar
                }
            }
            Section("Refresh") {
                Picker("Fetch new data every", selection: minutes) {
                    Text("1 minute").tag(1)
                    Text("2 minutes").tag(2)
                    Text("5 minutes").tag(5)
                    Text("10 minutes").tag(10)
                    Text("15 minutes").tag(15)
                }
            }
            if let onCheckForUpdates {
                Section("Updates") {
                    Button("Check for Updates…") { onCheckForUpdates() }
                    Text("New versions are also checked automatically at startup and once a week, and install without asking.")
                        .font(.caption).foregroundStyle(.secondary)
                }
            }
        }
        .formStyle(.grouped)
        .frame(width: 360)
    }

    /// `true` = the provider is shown; turning it off inserts it into the hidden set.
    private func providerBinding(_ p: Provider) -> Binding<Bool> {
        Binding(
            get: { !store.hiddenProviders.contains(p) },
            set: { shown in
                if shown {
                    store.hiddenProviders.remove(p)
                } else {
                    guard visibleCount > 1 else { return }
                    store.hiddenProviders.insert(p)
                }
            }
        )
    }

    private var minutes: Binding<Int> {
        Binding(
            get: { Int(store.refreshInterval / 60) },
            set: { store.refreshInterval = TimeInterval($0 * 60) }
        )
    }
}

/// The About window, opened from the popover's ⓘ button — the same mini page as
/// NeverSleep's (post-0.7.x standard, as also shipped in diskled-plus 0.9+): the
/// app icon at 96 pt, name, "Version x (build y)", the PayPal donation QR
/// (paypal-qr.png in Resources, generated by scripts/make-qr.swift; bundle copy
/// done in build-app.sh), © line with the operator's public identity (Marcus1571,
/// not the real name), the license, the GitHub repo, the bug-report block and a
/// one-line tagline.
struct AboutView: View {
    private var version: String {
        Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "?"
    }
    private var build: String {
        Bundle.main.infoDictionary?["CFBundleVersion"] as? String ?? "?"
    }

    var body: some View {
        VStack(spacing: 10) {
            Image(nsImage: NSApp.applicationIconImage)
                .resizable()
                .frame(width: 96, height: 96)
                .accessibilityLabel("UsageBar app icon")
            Text("UsageBar")
                .font(.title2).fontWeight(.bold)
            Text("Version \(version) (build \(build))")
                .font(.caption).foregroundColor(.secondary)
            Divider()
            supportSection
            Divider()
            Text("© 2026 Marcus1571").font(.subheadline)
            Text("MIT").font(.caption).foregroundColor(.secondary)
            Link("github.com/Marcus1571/usagebar",
                 destination: URL(string: "https://github.com/Marcus1571/usagebar")!)
                .font(.subheadline)
            bugSection
            Text("The remaining quota of your AI coding subscriptions — Claude, ChatGPT (Codex), Grok, OpenCode Go and GitHub Copilot — right in the menu bar. Read-only.")
                .font(.footnote).foregroundColor(.secondary)
                .multilineTextAlignment(.center)
        }
        .padding(24)
        .frame(width: 300)
    }

    /// Donation block: PayPal.me QR + tappable link (phones can't scan their
    /// own screen, so the link matters). QR is bundled as paypal-qr.png;
    /// when absent (bare `swift run`, no bundle) the block degrades to text.
    private var supportSection: some View {
        VStack(spacing: 5) {
            if let url = Bundle.main.url(forResource: "paypal-qr", withExtension: "png"),
               let qr = NSImage(contentsOf: url) {
                Image(nsImage: qr)
                    .resizable()
                    .interpolation(.high)
                    .frame(width: 88, height: 88)
                    .accessibilityLabel("PayPal donation QR code")
            }
            Text("Support UsageBar")
                .font(.subheadline).fontWeight(.semibold)
            Link("paypal.me/marcodalmoro",
                 destination: URL(string: "https://paypal.me/marcodalmoro")!)
                .font(.caption)
            Text("Point your phone's camera at the code — or tap the link.")
                .font(.caption2).foregroundColor(.secondary)
                .fixedSize(horizontal: false, vertical: true)   // must wrap, not truncate
                .multilineTextAlignment(.center)
        }
    }

    /// Bug-report block: ladybug + "Report a Bug" + a tappable link to the
    /// repo's Issues page — the same design as diskled-plus 0.10 and
    /// NeverSleep 0.8.
    private var bugSection: some View {
        VStack(spacing: 5) {
            HStack(spacing: 5) {
                Image(systemName: "ladybug.fill")
                Text("Report a Bug")
                    .font(.subheadline).fontWeight(.semibold)
            }
            Link("github.com/Marcus1571/usagebar/issues",
                 destination: URL(string: "https://github.com/Marcus1571/usagebar/issues")!)
                .font(.caption)
        }
    }
}
